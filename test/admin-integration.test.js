test('staff and customer share catalog, booking, payment and availability records',async t=>{
  const f=await fixture({},true);t.after(()=>f.close());
  const api=f.api;
  assert.equal((await api('/api/operator/overview')).status,401);
  const staff=(await api('/api/staff/login',{method:'POST',body:{email:'staff@example.test',password:'TestStaffPassword123!'}})).cookie;
  const client=(await api('/api/auth/signup',{method:'POST',body:{name:'Integration QA',email:'integration@example.test',password:'TestPassword123!'}})).cookie;
  const call=(url,method='GET',body)=>api('/api/operator'+url,{cookie:staff,method,body});
  assert.equal((await call('/staff-notices','PUT',{newBooking:true,paymentReceived:true,eventReminder:false,newReview:false,weeklySummary:false})).status,200);
  assert.equal((await call('/overview')).data.totals.net_collections_cents,0);
  const catalog=(await api('/api/catalog')).data;
  const rental=catalog.models[0];
  const offer=catalog.packages.find(p=>p.id===rental.booking_package_id);
  const selection={rentalId:rental.id,variantId:catalog.variants.find(v=>v.model_id===rental.id).id,
    name:'Integration QA',contact:'09123456789',venue:'Synthetic venue',eventDate:'2090-07-01',eventTime:'10:00',
    cityId:'quezon-city',notes:'Please quote custom accessories',reservationFeeAccepted:true};
  const reviewed=(await api('/api/quotes',{method:'POST',body:selection})).data.quote;
  const created=await api('/api/bookings',{method:'POST',cookie:client,body:{...selection,reviewToken:reviewed.review_token}});
  assert.equal(created.status,201,created.data.error);
  const ref=created.data.booking.reference;
  let record=(await call('/bookings?search='+ref)).data.bookings[0];
  assert.equal(record.reference,ref);
  assert.equal(record.quote.included_hours,4);
  assert.equal((await api('/api/availability?date='+selection.eventDate)).data.available,false);
  assert.equal((await call('/date-blocks','POST',{date:selection.eventDate,reason:'Conflict check'})).status,409);
  assert.equal((await call('/bookings/'+ref+'/quote','PUT',{total:'7000',note:'Synthetic quote accepted'})).status,200);
  assert.equal((await api('/api/bookings/'+ref,{cookie:client})).data.booking.total_cents,700000);
  assert.equal((await api('/api/bookings/'+ref+'/payments',{cookie:client,method:'POST',body:{amount:'3500',method:'GCash',reference:'INTEGRATION-REF'}})).status,201);
  const payment=(await call('/bookings/'+ref)).data.booking.payments[0];
  assert.equal(payment.status,'pending');
  assert.equal((await call('/overview')).data.totals.verified_collected_cents,0);
  assert.equal((await call('/payments/'+payment.id,'PUT',{status:'verified',note:'Checked synthetic payment'})).status,200);
  assert.equal((await call('/overview')).data.totals.net_collections_cents,350000);
  assert.equal((await api('/api/bookings/'+ref,{cookie:client})).data.booking.balance_cents,350000);
  assert.equal((await call('/bookings/'+ref+'/status','PUT',{status:'confirmed'})).status,200);
  assert.equal((await call('/bookings/'+ref+'/reschedule','POST',{eventDate:'2090-07-02',eventTime:'11:00'})).status,200);
  assert.equal((await api('/api/availability?date='+selection.eventDate)).data.available,true);
  assert.equal((await api('/api/availability?date=2090-07-02')).data.available,false);
  assert.equal((await call('/catalog/packages/'+offer.id+'/pricing','PUT',{price:'6600',hours:5,inclusions:['Setup'],modelIds:[rental.id]})).status,200);
  const repriced=await api('/api/bookings',{method:'POST',cookie:client,body:{...selection,reviewToken:reviewed.review_token}});
  assert.equal(repriced.status,409);
  assert.match(repriced.data.error,/Pricing changed/);
  assert.equal((await api('/api/quotes',{method:'POST',body:selection})).data.quote.included_hours,5);
  record=(await call('/bookings/'+ref)).data.booking;
  assert.equal(record.quote.included_hours,4);
  assert.equal((await call('/bookings/'+ref+'/status','PUT',{status:'cancelled',reason:'Synthetic cancellation'})).status,200);
  assert.equal((await call('/overview')).data.totals.outstanding_cents,0);
  assert.equal((await call('/overview')).data.totals.unresolved_inactive_cents,350000);
  assert.equal((await call('/payments/'+payment.id,'PUT',{status:'refunded',note:'Synthetic external refund'})).status,200);
  const metrics=(await call('/overview')).data.totals;
  assert.equal(metrics.gross_collections_cents,350000);assert.equal(metrics.net_collections_cents,0);
  assert.equal(metrics.recorded_refunded_cents,350000);
  assert.equal((await call('/reports')).data.net_collections_cents,metrics.net_collections_cents);
  const outbox=(await call('/notifications')).data.notifications;
  assert.equal(outbox.filter(n=>n.kind==='staff.newBooking').length,1);
  assert.equal(outbox.filter(n=>n.kind==='staff.paymentReceived').length,1);
  assert.ok((await call('/audit')).data.events.some(e=>e.action==='payment.verified'&&e.actor.startsWith('staff:')));

  const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Manila',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
  const reminderDate=new Date(Date.parse(today+'T00:00:00Z')+2*86400000).toISOString().slice(0,10);
  assert.equal((await call('/staff-notices','PUT',{newBooking:false,paymentReceived:false,eventReminder:true,newReview:false,weeklySummary:false})).status,200);
  const next=await api('/api/bookings',{method:'POST',cookie:client,body:{...selection,eventDate:reminderDate,notes:''}});
  assert.equal(next.status,201);
  const nextRef=next.data.booking.reference;
  const recordedReference={amount:'3400',method:'GCash',reference:'REMINDER-TEST'};
  assert.equal((await api('/api/operator/bookings/'+nextRef+'/payments',{cookie:client,method:'POST',body:recordedReference})).status,401);
  const deposit=await call('/bookings/'+nextRef+'/payments','POST',recordedReference);
  assert.equal(deposit.status,201);
  const nextPayment=(await call('/bookings/'+nextRef)).data.booking.payments[0];
  assert.equal(nextPayment.status,'pending');
  assert.equal((await call('/payments/'+nextPayment.id,'PUT',{status:'verified',note:'Synthetic reminder verification'})).status,200);
  assert.equal((await call('/bookings/'+nextRef+'/status','PUT',{status:'confirmed'})).status,200);
  for(let i=0;i<2;i++)assert.equal((await call('/maintenance','POST',{})).status,200);
  assert.equal((await call('/notifications')).data.notifications.filter(n=>n.kind==='staff.eventReminder').length,1);
});

test('legacy articles and saved settings survive startup and staff moderation reaches public reviews',async t=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'bb-content-integration-'));
  const opts={BOUNCEBASH_DB_PATH:path.join(temp,'data.sqlite'),PGLITE_PATH:path.join(temp,'postgres')};
  let f;
  t.after(async()=>{try{await f?.close();}finally{fs.rmSync(temp,{recursive:true,force:true});}});
  f=await fixture(opts,true);
  const staff=(await f.api('/api/staff/login',{method:'POST',body:{email:'staff@example.test',password:'TestStaffPassword123!'}})).cookie;
  const call=(url,method='GET',body)=>f.api('/api/operator'+url,{cookie:staff,method,body});
  assert.equal((await f.api('/api/operator/articles')).status,401);
  const articles=(await call('/articles')).data.articles;
  assert.equal(articles.length,7);
  assert.ok(articles.every(a=>a.provenance==='legacy-customer-site'&&a.blocks.length));
  const original=articles[0];
  const route='/articles/'+original.slug;
  const changes={title:'Synthetic edited article',summary:original.summary,category:original.category,dateLabel:original.date_label,image:original.image,imageAlt:original.image_alt,state:'draft',revision:original.revision};
  assert.equal((await call(route,'PUT',changes)).status,200);
  assert.equal((await f.api('/api'+route)).status,404);
  assert.equal((await call(route,'PUT',changes)).status,409);
  assert.equal((await call(route,'PUT',{...changes,state:'published',revision:changes.revision+1})).status,200);
  assert.equal((await f.api('/api'+route)).data.article.url,original.url);
  assert.equal((await call('/business-settings','PUT',{name:'Synthetic Business',email:'desk@example.test',area:'NCR',bankName:'Private Unapproved Draft'})).status,200);
  assert.equal((await f.api('/api/business-settings')).data.settings.payment.bank,null);
  const feedback=await f.api('/api/reviews',{method:'POST',body:{name:'Integration Reviewer',message:'Original text remains intact.',rating:5,canFeature:true}});
  assert.equal(feedback.status,201);
  const review='/reviews/'+feedback.data.reviewId;
  assert.equal((await call(review+'/editorial','PUT',{featured:true,archived:false,correction:''})).status,409);
  assert.equal((await call(review,'PUT',{status:'approved'})).status,200);
  assert.equal((await call(review+'/editorial','PUT',{featured:false,archived:false,correction:'Editorial note'})).status,200);
  assert.equal((await f.api('/api/reviews?featured=true')).data.total,0);
  assert.equal((await f.api('/api/reviews')).data.reviews[0].message,'Original text remains intact.');
  assert.equal((await call(review+'/editorial','PUT',{featured:false,archived:true,correction:'Editorial note'})).status,200);
  assert.equal((await f.api('/api/reviews')).data.total,0);
  await f.close();f=null;
  f=await fixture(opts);
  assert.equal((await f.api('/api/articles')).data.articles.length,7);
  assert.equal((await f.api('/api'+route)).data.article.title,'Synthetic edited article');
  assert.equal((await f.api('/api/business-settings')).data.settings.contact.name,'Synthetic Business');
});

